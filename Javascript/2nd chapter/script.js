//arithmetic operator
let a = 5;
let b = 3;
let c = a+b;

console.log("a + b ",a+b);
console.log("a + b ",c);
console.log("a % b ",a%b);
console.log("a / b ",a/b);
console.log("a * b ",a*b);
console.log("a ** b ",a**b);

//Unary Operator

let d = 7;
let e = 8;

console.log("d--",d--);//pre-decrement
console.log("d=",d);

console.log("--d",--d);//post-decrement
console.log("d=",d);


console.log("e++",e++);//pre-increment
console.log("e=",e);
console.log("++e",++e);//post-increment
console.log("e=",e);

